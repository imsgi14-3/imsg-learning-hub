// Build question-bank/similarity-pairs.json from a similarity audit CSV
// (e.g. chemistry_v3.5_similarity_audit.csv from the v3.5 audit zip).
//
// Usage:
//   node tools/build-similarity-pairs.js <audit.csv> [out.json]
//
// The output keeps ONLY the two question ids and the similarity score so the
// shipped file stays small. Threshold enforcement happens at runtime in
// similarity.js (DEFAULT_THRESHOLD), so every pair >= MIN_SIMILARITY below is
// kept and the cut-off can be tuned without regenerating the data.

var fs = require("fs");
var path = require("path");

var MIN_SIMILARITY = 0.9;

// Minimal RFC-4180 style CSV parser: quoted fields, "" escapes, commas and
// newlines inside quotes. The audit CSV is generated by pandas and fits this.
function parseCsv(text) {
    var rows = [];
    var row = [];
    var field = "";
    var inQuotes = false;
    for (var i = 0; i < text.length; i++) {
        var c = text[i];
        if (inQuotes) {
            if (c === '"') {
                if (text[i + 1] === '"') { field += '"'; i++; }
                else inQuotes = false;
            } else field += c;
        } else if (c === '"') {
            inQuotes = true;
        } else if (c === ",") {
            row.push(field); field = "";
        } else if (c === "\n") {
            row.push(field); field = ""; rows.push(row); row = [];
        } else if (c === "\r") {
            // skip; \n handles the row break
        } else {
            field += c;
        }
    }
    if (field !== "" || row.length) { row.push(field); rows.push(row); }
    return rows;
}

function main() {
    var csvPath = process.argv[2];
    if (!csvPath) {
        console.error("Usage: node tools/build-similarity-pairs.js <audit.csv> [out.json]");
        process.exit(1);
    }
    var outPath = process.argv[3] || path.join(__dirname, "..", "question-bank", "similarity-pairs.json");

    var text = fs.readFileSync(csvPath, "utf8");
    var rows = parseCsv(text);
    if (rows.length < 2) { console.error("No data rows found in " + csvPath); process.exit(1); }

    var header = rows[0];
    var col = {};
    for (var i = 0; i < header.length; i++) col[header[i].trim()] = i;
    var need = ["similarity", "id_1", "id_2"];
    for (var n = 0; n < need.length; n++) {
        if (col[need[n]] === undefined) { console.error("CSV is missing column: " + need[n]); process.exit(1); }
    }

    var seen = {};
    var pairs = [];
    var skipped = 0;
    for (var r = 1; r < rows.length; r++) {
        var row = rows[r];
        if (!row || row.length < header.length) continue;
        var s = parseFloat(row[col.similarity]);
        var a = (row[col.id_1] || "").trim();
        var b = (row[col.id_2] || "").trim();
        if (isNaN(s) || !a || !b || a === b) { skipped++; continue; }
        if (s < MIN_SIMILARITY) continue;
        // Order-independent key so a pair listed twice is stored once.
        var key = a < b ? a + "|" + b : b + "|" + a;
        if (seen[key]) { skipped++; continue; }
        seen[key] = true;
        pairs.push({ a: a, b: b, s: Math.round(s * 10000) / 10000 });
    }

    pairs.sort(function(x, y) { return y.s - x.s || (x.a < y.a ? -1 : x.a > y.a ? 1 : 0); });

    var head = {
        source: path.basename(csvPath),
        minSimilarity: MIN_SIMILARITY,
        pairCount: pairs.length
    };
    // Pretty header + one pair per line: small file, readable diffs.
    var lines = pairs.map(function(p) { return JSON.stringify(p); });
    var json = JSON.stringify(head, null, 2).slice(0, -2) + ',\n  "pairs": [\n    ' +
        lines.join(",\n    ") + "\n  ]\n}\n";
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, json, "utf8");
    console.log("Wrote " + pairs.length + " pairs (>= " + MIN_SIMILARITY + ") to " + outPath +
        (skipped ? " [skipped " + skipped + " malformed/duplicate rows]" : ""));
}

main();
